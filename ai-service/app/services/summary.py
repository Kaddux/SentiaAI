"""Daily + weekly summary generation (plan Section 7, phase 7).

Summaries are generated by the LLM over structured health data (snapshot +
baseline + trends) and stored in ai_schema.daily_summaries / weekly_summaries.
The LLM is never shown raw sensor streams.
"""

from __future__ import annotations

import json
import logging
import uuid
from datetime import date, timedelta

from sqlalchemy import delete, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.services.database import DailySummary, WeeklySummary
from app.services.health_client import health_client
from app.services.llm_client import chat_with_fallback

log = logging.getLogger("sentiaai.summary")

SUMMARY_SYSTEM = (
    "You are Sentia AI writing a short, warm, personal daily health summary.\n"
    "Use ONLY the data below. Do not invent readings. Keep it non-diagnostic and "
    "encourage professional support if something looks concerning. 4-6 sentences, "
    "then 1-3 short bullet recommendations."
)

WEEKLY_SYSTEM = (
    "You are Sentia AI writing a short weekly health recap.\n"
    "Use ONLY the data below. Non-diagnostic, warm, concise. Summarize trends "
    "and give 2-3 gentle recommendations. 5-7 sentences."
)


def _uid(user_id: str) -> uuid.UUID:
    return uuid.UUID(str(user_id))


async def _llm(payload: dict, weekly: bool = False) -> str:
    system = WEEKLY_SYSTEM if weekly else SUMMARY_SYSTEM
    prompt = f"{system}\n\n<data>\n{json.dumps(payload, default=str)}\n</data>"
    resp = await chat_with_fallback([{"role": "system", "content": prompt}])
    return (resp.choices[0].message.content or "").strip()


def _pick(snapshot: dict, *keys: str):
    cur = snapshot
    for k in keys:
        if isinstance(cur, dict):
            cur = cur.get(k)
        else:
            return None
    return cur


async def generate_daily_summary(db: AsyncSession, user_id: str, jwt: str, d: date) -> dict:
    uid = _uid(user_id)
    snapshot = await health_client.health_snapshot(jwt, d.isoformat())
    baseline = await health_client.baseline(jwt)

    text = await _llm({"date": str(d), "snapshot": snapshot, "baseline": baseline})

    await db.execute(delete(DailySummary).where(
        DailySummary.user_id == uid, DailySummary.summary_date == d))
    db.add(DailySummary(
        user_id=uid, summary_date=d, version=1,
        sleep_hours=_pick(snapshot, "sleep", "duration_hours"),
        steps=_pick(snapshot, "activity", "steps"),
        resting_hr=_pick(snapshot, "heart_rate", "resting"),
        avg_hr=_pick(snapshot, "heart_rate", "average"),
        max_hr=_pick(snapshot, "heart_rate", "max"),
        active_minutes=_pick(snapshot, "activity", "active_minutes"),
        temperature_avg=_pick(snapshot, "temperature", "average"),
        summary_text=text,
        health_context={"snapshot": snapshot, "baseline": baseline},
    ))
    await db.commit()
    return {"date": str(d), "summary_text": text}


async def generate_weekly_summary(db: AsyncSession, user_id: str, jwt: str, week_start: date) -> dict:
    uid = _uid(user_id)
    week_end = week_start + timedelta(days=6)
    baseline = await health_client.baseline(jwt)
    trend = await health_client.trends(jwt, "sleep", 7)
    payload = {"week_start": str(week_start), "week_end": str(week_end),
               "baseline": baseline, "sleep_trend": trend}

    text = await _llm(payload, weekly=True)

    await db.execute(delete(WeeklySummary).where(
        WeeklySummary.user_id == uid, WeeklySummary.week_start == week_start))
    db.add(WeeklySummary(
        user_id=uid, week_start=week_start, week_end=week_end, version=1,
        summary_text=text, vs_previous_week=payload,
    ))
    await db.commit()
    return {"week_start": str(week_start), "week_end": str(week_end), "summary_text": text}


async def get_daily_summary(db: AsyncSession, user_id: str, jwt: str, d: date) -> dict:
    uid = _uid(user_id)
    row = (await db.execute(select(DailySummary).where(
        DailySummary.user_id == uid, DailySummary.summary_date == d))).scalar_one_or_none()
    if row is not None:
        return {"date": str(d), "summary_text": row.summary_text}
    return await generate_daily_summary(db, user_id, jwt, d)


async def get_weekly_summary(db: AsyncSession, user_id: str, jwt: str, week_start: date) -> dict:
    uid = _uid(user_id)
    row = (await db.execute(select(WeeklySummary).where(
        WeeklySummary.user_id == uid, WeeklySummary.week_start == week_start))).scalar_one_or_none()
    if row is not None:
        return {"week_start": str(week_start), "week_end": str(row.week_end), "summary_text": row.summary_text}
    return await generate_weekly_summary(db, user_id, jwt, week_start)
